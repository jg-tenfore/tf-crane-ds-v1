// Generates src/styles/club-theme.css: the rules that let <ClubTheme> re-colour a subtree.
//
// Why: semantic tokens (--color-bg-brand-solid, --color-text-brand-secondary …) are declared once on
// :root as var(--color-brand-600) etc. A custom property that references another is resolved where it
// is declared, so setting --color-brand-* on a wrapper alone changes nothing below it. This file
// re-declares every token that (directly or through another token) depends on --color-brand-*, inside
// `.club-theme`, so it re-resolves against the wrapper's ramp. Dark mode gets the same treatment from
// the `.dark-mode` block.
//
// Re-run after changing src/styles/theme.css:  node scripts/gen-club-theme-css.mjs
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../src/styles/theme.css", import.meta.url), "utf8");

/** All `--name: value;` declarations inside the first top-level block that starts at `open`. */
const block = (start) => {
    let depth = 0;
    let i = css.indexOf("{", start);
    const from = i + 1;
    for (; i < css.length; i++) {
        if (css[i] === "{") depth++;
        else if (css[i] === "}" && --depth === 0) break;
    }
    return css.slice(from, i);
};
const decls = (text) => [...text.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => ({ name, value: value.trim() }));

const light = decls(block(css.indexOf("@theme")));
const dark = decls(block(css.indexOf(".dark-mode {")));

/** Names whose value depends on --color-brand-* (transitively), excluding the ramp itself. */
const dependents = (list, extraKnown = new Set()) => {
    const byName = new Map(list.map((d) => [d.name, d]));
    const deps = new Set(extraKnown);
    let changed = true;
    const isRamp = (n) => /^--color-brand-\d+$/.test(n);
    while (changed) {
        changed = false;
        for (const d of byName.values()) {
            if (isRamp(d.name) || deps.has(d.name)) continue;
            const refs = [...d.value.matchAll(/var\((--[\w-]+)/g)].map((m) => m[1]);
            if (refs.some((r) => isRamp(r) || deps.has(r))) {
                deps.add(d.name);
                changed = true;
            }
        }
    }
    return list.filter((d) => deps.has(d.name));
};

const lightDeps = dependents(light);
// In dark mode a token can depend on brand through a light-mode token (e.g. var(--color-bg-brand-solid)).
const darkDeps = dependents(dark, new Set(lightDeps.map((d) => d.name)));

const body = (list) => list.map((d) => `    ${d.name}: ${d.value};`).join("\n");
const out = `/* GENERATED by scripts/gen-club-theme-css.mjs from src/styles/theme.css. Do not edit by hand.
   Re-declares every brand-dependent token inside .club-theme so a club palette (inline --color-brand-*
   on the wrapper, see src/components/club-theme/club-theme.tsx) re-colours the subtree, light and dark. */

.club-theme {
${body(lightDeps)}
}

.dark-mode .club-theme,
.club-theme.dark-mode,
.club-theme .dark-mode {
${body(darkDeps)}
}
`;
writeFileSync(new URL("../src/styles/club-theme.css", import.meta.url), out);
console.log(`✓ src/styles/club-theme.css — ${lightDeps.length} light, ${darkDeps.length} dark tokens`);
